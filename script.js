function preserveWhitespace(original, translated) {
  const leading = original.match(/^\s*/)[0];
  const trailing = original.match(/\s*$/)[0];
  return `${leading}${translated}${trailing}`;
}

function translateTextNodes(root, lang) {
  const map = textTranslations[lang] || {};
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const parent = node.parentElement;
      if (!parent || ["SCRIPT", "STYLE", "TEXTAREA"].includes(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    }
  });

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    const key = node.nodeValue.trim().replace(/\s+/g, " ");
    if (map[key]) node.nodeValue = preserveWhitespace(node.nodeValue, map[key]);
  });
}

function translateAttributes(lang) {
  const map = placeholderTranslations[lang] || {};
  document.querySelectorAll("[placeholder]").forEach((element) => {
    const current = element.getAttribute("placeholder");
    if (map[current]) element.setAttribute("placeholder", map[current]);
  });

  document.querySelectorAll("[alt]").forEach((element) => {
    const current = element.getAttribute("alt");
    if (textTranslations[lang][current]) element.setAttribute("alt", textTranslations[lang][current]);
  });
}

function setTitle(lang) {
  let path = window.location.pathname;
  if (path === "/" || path.endsWith("/")) path = "/index.html";
  const page = `/${path.split("/").pop()}`;
  if (titleTranslations[lang] && titleTranslations[lang][page]) {
    document.title = titleTranslations[lang][page];
  }
}

function applyLanguage(lang) {
  document.documentElement.lang = lang === "zh" ? "zh-TW" : "en";
  translateTextNodes(document.body, lang);
  translateAttributes(lang);
  setTitle(lang);
  localStorage.setItem("siteLanguage", lang);

  document.querySelectorAll("[data-lang-option]").forEach((button) => {
    button.classList.toggle("active", button.dataset.langOption === lang);
    button.setAttribute("aria-pressed", button.dataset.langOption === lang ? "true" : "false");
  });
}

function addLanguageSwitcher() {
  const nav = document.querySelector("[data-nav-links]");
  if (!nav || nav.querySelector(".language-switch")) return;

  const switcher = document.createElement("div");
  switcher.className = "language-switch";
  switcher.setAttribute("aria-label", "Language");
  switcher.innerHTML = `
    <button type="button" data-lang-option="en">English</button>
    <button type="button" data-lang-option="zh">繁中</button>
  `;

  const cta = nav.querySelector(".btn");
  if (cta) nav.insertBefore(switcher, cta);
  else nav.appendChild(switcher);

  switcher.querySelectorAll("button").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.langOption));
  });
}

function setActiveNavLink() {
  const page = window.location.pathname.split("/").pop() || "index.html";
  document.querySelectorAll(".nav-links a[href]").forEach((link) => {
    const href = link.getAttribute("href");
    if (href === page || (page === "" && href === "index.html")) {
      link.classList.add("nav-active");
      link.setAttribute("aria-current", "page");
    }
  });
}

